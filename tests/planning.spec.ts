import { expect, test } from '@playwright/test'

test('private planning consent, kit edit, crisis restore, travel lookup and erase', async ({page})=>{
  const searched:string[]=[]
  await page.route('**/api/resources/needs?*',async route=>{
    searched.push(new URL(route.request().url()).searchParams.get('zip') || '')
    await route.fulfill({json:{status:'ok',kinds:{food:{status:'ok',results:[{kind:'food',name:'Example pantry',source:'Test directory',address:'Example street',distanceMiles:1}],fallback:[]}}}})
  })
  await page.goto('/planning')
  await expect(page.getByRole('heading',{name:'Private planning'})).toBeVisible()
  await expect(page.getByLabel('Home ZIP')).toHaveCount(0)
  await page.getByRole('button',{name:'Enable local planning'}).click()
  await page.getByLabel('Home ZIP').fill('10001')
  await page.getByRole('button',{name:'Save home ZIP'}).click()
  await page.getByLabel('Destination ZIP').fill('90210')
  await page.getByLabel('Travel ends').fill(new Date(Date.now()+86400000).toISOString().slice(0,16))
  await page.getByRole('button',{name:'Start travel mode'}).click()
  await page.getByRole('button',{name:'Find resources for active ZIP'}).click()
  await expect(page.getByText('Example pantry',{exact:true})).toBeVisible()
  expect(searched.at(-1)).toBe('90210')
  await page.getByRole('button',{name:'Return home / cancel travel'}).click()
  await expect.poll(()=>searched.at(-1)).toBe('10001')
  await page.getByLabel('Kit location label').fill('Blue bag')
  await page.getByRole('button',{name:'Save kit'}).click()
  await expect(page.getByText('Blue bag',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Edit kit Blue bag'}).click()
  await page.getByLabel('Kit location label').fill('Kitchen shelf')
  await page.getByRole('button',{name:'Save kit'}).click()
  await expect(page.getByText('Kitchen shelf',{exact:true})).toBeVisible()
  await page.getByLabel('First steps').fill('My first step')
  await page.getByRole('button',{name:'Save crisis-plan version'}).click()
  await page.getByLabel('First steps').fill('My changed step')
  await page.getByRole('button',{name:'Save crisis-plan version'}).click()
  await page.getByRole('button',{name:'Restore version 1'}).click()
  await expect(page.getByLabel('First steps')).toHaveValue('My first step')
  await page.getByRole('button',{name:'Erase all private planning data'}).click()
  await expect(page.getByRole('button',{name:'Enable local planning'})).toBeVisible()
  expect(await page.evaluate(()=>localStorage.getItem('narcoguard_private_planning_v1'))).toBeNull()
})

