test('another tab erases consent, drafts and prevents expiry from restoring old data',async({page,context})=>{
  await page.goto('/planning')
  await page.getByRole('button',{name:'Enable local planning'}).click()
  await page.getByLabel('Destination ZIP').fill('90210')
  await page.getByLabel('Travel ends').fill(new Date(Date.now()+3600000).toISOString().slice(0,16))
  await page.getByRole('button',{name:'Start travel mode'}).click()
  const other=await context.newPage()
  await other.goto('/planning')
  await expect(other.getByLabel('Kit location label')).toBeVisible()
  await other.getByLabel('Kit location label').fill('Unsaved private draft')
  await other.getByLabel('First steps').fill('Unsaved crisis draft')
  await page.getByRole('button',{name:'Erase all private planning data'}).click()
  await expect(other.getByRole('button',{name:'Enable local planning'})).toBeVisible()
  await other.clock.install()
  await other.clock.fastForward(2*3600000)
  expect(await other.evaluate(()=>localStorage.getItem('narcoguard_private_planning_v1'))).toBeNull()
  await other.reload()
  await expect(other.getByRole('button',{name:'Enable local planning'})).toBeVisible()
  expect(await other.evaluate(()=>localStorage.getItem('narcoguard_private_planning_v1'))).toBeNull()
  await other.getByRole('button',{name:'Enable local planning'}).click()
  await expect(other.getByLabel('Kit location label')).toHaveValue('')
  await expect(other.getByLabel('First steps')).toHaveValue('')
  await expect(other.getByLabel('Destination ZIP')).toHaveValue('')
})

test('real Web Lock queues erase before a stale tab save without resurrecting storage',async({page,context})=>{
  await page.goto('/planning')
  await page.getByRole('button',{name:'Enable local planning'}).click()
  await expect(page.getByLabel('Home ZIP')).toBeVisible()
  const other=await context.newPage();await other.goto('/planning')
  await expect(other.getByLabel('Home ZIP')).toBeVisible()
  await other.getByLabel('Home ZIP').fill('90210')
  const controller=await context.newPage();await controller.goto('/help')
  await controller.evaluate(()=>new Promise<void>(started=>{
    void navigator.locks.request('narcoguard-private-planning',async()=>{
      await new Promise<void>(release=>{
        ;(window as unknown as {releasePlanningLock:()=>void}).releasePlanningLock=release
        started()
      })
    })
  }))
  await page.getByRole('button',{name:'Erase all private planning data'}).click()
  // Wait until erase is actually queued behind the controller's exclusive lock.
  await expect.poll(()=>controller.evaluate(async()=> (await navigator.locks.query()).pending?.length ?? 0)).toBeGreaterThan(0)
  await other.getByRole('button',{name:'Save home ZIP'}).click()
  await expect.poll(()=>controller.evaluate(async()=> (await navigator.locks.query()).pending?.length ?? 0)).toBeGreaterThan(1)
  await controller.evaluate(()=> (window as unknown as {releasePlanningLock:()=>void}).releasePlanningLock())
  await expect(page.getByRole('button',{name:'Enable local planning'})).toBeVisible()
  await expect(other.getByRole('button',{name:'Enable local planning'})).toBeVisible()
  expect(await other.evaluate(()=>localStorage.getItem('narcoguard_private_planning_v1'))).toBeNull()
  await other.reload()
  await expect(other.getByRole('button',{name:'Enable local planning'})).toBeVisible()
})

test('without Web Locks persistence fails closed while public help stays accessible',async({page})=>{
  await page.addInitScript(()=>Object.defineProperty(navigator,'locks',{value:undefined,configurable:true}))
  await page.goto('/planning')
  await page.getByRole('button',{name:'Enable local planning'}).click()
  await expect(page.getByText(/Web Locks are unavailable/)).toBeVisible()
  await expect(page.getByRole('link',{name:'Find resources without saving a plan'})).toHaveAttribute('href','/help')
  await expect(page.getByLabel('Home ZIP')).toHaveCount(0)
  expect(await page.evaluate(()=>localStorage.getItem('narcoguard_private_planning_v1'))).toBeNull()
})
