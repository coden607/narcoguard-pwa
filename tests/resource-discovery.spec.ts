import { expect, test } from "@playwright/test"

test("official meeting discovery preserves local provenance, cancellation, and erasure", async ({ page }) => {
  await page.goto("/meetings")
  await expect(page.getByRole("link", { name: "Find meetings with SMART Recovery USA" })).toHaveAttribute("href", "https://meetings.smartrecovery.org/meetings/")
  await page.getByLabel("Meeting name", { exact: true }).fill("Example provider listing")
  await page.getByLabel("Public provider listing URL").fill("https://meetings.smartrecovery.org/meetings/123/")
  await page.getByLabel("Schedule exactly as listed").fill("Tuesday 18:00")
  await page.getByLabel("Schedule timezone").fill("America/New_York")
  await page.getByLabel("Provider update date").fill("2026-10-16")
  await page.getByLabel("Date you checked the source").fill("2026-10-17")
  await page.getByLabel("Status according to the source").selectOption("cancelled")
  await page.getByRole("button", { name: "Save meeting details", exact: true }).click()
  await expect(page.getByText("Cancelled according to saved source", { exact: true })).toBeVisible()
  await expect(page.getByText("Schedule: Tuesday 18:00 · Timezone: America/New_York")).toBeVisible()
  await page.reload()
  await expect(page.getByText("Cancelled according to saved source", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Edit Example provider listing" }).click()
  await page.getByLabel("Schedule timezone").fill("")
  await page.getByLabel("Status according to the source").selectOption("unknown")
  await page.getByRole("button", { name: "Save meeting details", exact: true }).click()
  await expect(page.getByText("Meeting status unknown — confirm with provider", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Erase all saved meeting details" }).click()
  await page.reload()
  await expect(page.getByText("No meeting details saved.", { exact: true })).toBeVisible()
})

test("resource accessibility stays unknown and contribution errors never claim publication", async ({ page }) => {
  await page.route("**/api/resources/understand", (route) => route.fulfill({ json: { available: false } }))
  await page.route("**/api/resources/needs?*", (route) => route.fulfill({ json: { status: "ok", kinds: { food: { status: "ok", results: [{ name: "Test pantry", kind: "food", source: "OpenStreetMap contributors", wheelchair: "yes" }], fallback: [] } } } }))
  await page.route("**/api/resources/corrections?*", (route) => route.fulfill({ json: { corrections: [{ id: "correction", proposed_text: "Provider says quiet room requires advance booking.", source_url: "https://example.org/access", created_at: "2026-10-17" }] } }))
  await page.route("**/api/resources/reports", async (route) => {
    const body = route.request().postDataJSON()
    expect(body.resourceRef).toContain("OpenStreetMap contributors:")
    expect(body.details).toContain("Provider website")
    expect(body.details).toContain("2026-10-17")
    await route.fulfill({ status: 401, json: { error: "Sign in to file a report." } })
  })
  await page.goto("/help")
  await page.getByRole("textbox", { name: "ZIP code" }).fill("10001")
  await page.getByRole("button", { name: "Search", exact: true }).click()
  const group = page.getByTestId("need-food")
  await group.locator(":scope > summary").click()
  await group.getByText("Accessibility details and contributions", { exact: true }).click()
  await expect(group.getByText("Unknown · Source: not provided · Updated: unknown", { exact: true })).toHaveCount(4)
  await expect(group.getByText("Provider says quiet room requires advance booking.")).toBeVisible()
  await group.getByText("Contribute accessibility information for review", { exact: true }).click()
  await group.getByLabel("Provenance: provider URL").fill("Provider website https://example.org/access")
  await group.getByLabel("Date observed or confirmed with source").fill("2026-10-17")
  await group.getByRole("button", { name: "Submit for review" }).click()
  await expect(group.getByRole("status")).toContainText("Sign in to submit")
  await expect(group.getByLabel("Provenance: provider URL")).toHaveValue("Provider website https://example.org/access")
})
